'use strict';

// Run one seeded defect at a time and check that the intended test catches it.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { DEFECTS } = require('../src/defects');

const ROOT = path.resolve(__dirname, '..');
const RESULTS_FILE = path.join(ROOT, 'reports', 'results.json');

// Expected failing scenario for each deliberate defect.
const EXPECTED = {
  'auth-not-required': '15',
  'ownership-not-checked': '16',
  'declined-payment-captured': '13',
  'double-payment-allowed': '14',
  'captured-on-request': '01',
  'capture-timeout-missing': '11',
  'late-capture-rejected': '12',
  'duplicate-events-reapplied': '07',
  'out-of-order-event-applied': '09',
  'refund-limit-ignored': '03',
  'refund-before-capture-allowed': '04',
  'refunded-total-wrong': '01',
  'failed-refund-keeps-reservation': '06',
  'history-entry-missing': '01',
};

function runPlaywright(env) {
  const result = spawnSync('npx', ['playwright', 'test'], {
    cwd: ROOT,
    env: { ...process.env, ...env },
    stdio: 'ignore',
    shell: process.platform === 'win32',
  });
  const report = JSON.parse(fs.readFileSync(RESULTS_FILE, 'utf8'));
  return { exitCode: result.status, report };
}

/** The scenario numbers (the "NN-" prefix of a spec file) in which at least
 * one test failed. */
function failedScenarioNumbers(report) {
  const numbers = new Set();
  function walk(suite) {
    for (const spec of suite.specs ?? []) {
      const failed = (spec.tests ?? []).some((t) =>
        (t.results ?? []).some((r) => !['passed', 'skipped'].includes(r.status)),
      );
      if (failed) {
        const match = /(\d{2})-/.exec(path.basename(suite.file ?? spec.file ?? ''));
        if (match) numbers.add(match[1]);
      }
    }
    for (const child of suite.suites ?? []) walk(child);
  }
  for (const suite of report.suites ?? []) walk(suite);
  return numbers;
}

function main() {
  const missing = Object.keys(DEFECTS).filter((name) => !EXPECTED[name]);
  if (missing.length > 0) throw new Error(`No expected scenario for: ${missing.join(', ')}`);

  const clean = runPlaywright({});
  if (clean.exitCode !== 0) {
    throw new Error('The suite fails with no defect switched on, so this check means nothing.');
  }

  const rows = [];
  for (const [name, description] of Object.entries(DEFECTS)) {
    const { report } = runPlaywright({ SEEDED_DEFECT: name });
    const numbers = [...failedScenarioNumbers(report)];
    const caught = numbers.includes(EXPECTED[name]);
    rows.push({ name, description, caught, numbers });
    console.log(
      `${caught ? 'CAUGHT' : 'MISSED'}  ${name}  ->  scenario(s) ${numbers.join(', ') || 'none'} failed`,
    );
  }

  const caughtCount = rows.filter((row) => row.caught).length;
  const reportMd = [
    '# Seeded defect results (Playwright)',
    '',
    'Generated by `npm run test:defects`. Each row is a full run of the suite against the service with one deliberate bug switched on.',
    '',
    `**${caughtCount} of ${rows.length} caught by the scenario meant to catch them.** The suite also passed with no bug switched on.`,
    '',
    '| Deliberate bug | Caught? | Scenarios that failed |',
    '|---|---|---|',
    ...rows.map(
      (row) =>
        `| ${row.description} | ${row.caught ? 'Yes' : '**No**'} | ${row.numbers.join(', ') || 'None'} |`,
    ),
    '',
    'These are bugs I chose, so this shows the suite catches these failures. It does not show that the suite would catch every possible bug.',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, 'docs', 'defect-results.md'), reportMd);

  console.log(`\n${caughtCount} of ${rows.length} caught.`);
  process.exitCode = caughtCount === rows.length ? 0 : 1;
}

main();
